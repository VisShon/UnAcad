package edu.univ.erp.domain;

public class Settings {

    private String key;
    private String value;

    // --- Getters and Setters ---

    public String getKey() {
        return key;
    }

    public void setKey(String key) {
        this.key = key;
    }

    public String getValue() {
        return value;
    }

    public void setValue(String value) {
        this.value = value;
    }
}